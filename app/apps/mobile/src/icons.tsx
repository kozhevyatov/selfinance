/** Иконка категории в цветном кружке. */
export function CatIcon({ name, color, size = 40 }: { name: string | null | undefined; color?: string | null; size?: number }) {
  const t = useTheme();
  const I = (name && ICONS[name]) || Ellipsis;
  const c = color || t.muted;
  return (
    <View
      style={{
        width: size,
        height: size,
        borderRadius: size / 2,
        backgroundColor: /^#[0-9a-f]{6}$/i.test(c) ? c + (t.dark ? '33' : '1F') : t.input,
        alignItems: 'center',
        justifyContent: 'center',
      }}
    >
      <I size={size * 0.48} color={c} strokeWidth={1.8} />
    </View>
  );
}
